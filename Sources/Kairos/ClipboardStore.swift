import AppKit
import CryptoKit
import ImageIO
import Observation

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    let id: UUID
    var kind: Kind
    var text: String? = nil        // .text
    var paths: [String]? = nil     // .files
    var imageFile: String? = nil   // .image, file name inside the images folder
    var width: Int? = nil
    var height: Int? = nil
    var digest: String             // identity used to de-duplicate
    var date: Date

    var searchText: String {
        switch kind {
        case .text: text ?? ""
        case .files: (paths ?? []).map { ($0 as NSString).lastPathComponent }.joined(separator: " ")
        case .image: "image"
        }
    }
}

@MainActor
@Observable
final class ClipboardStore {
    private(set) var items: [ClipItem] = []

    @ObservationIgnored private let settings: Settings
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private let historyURL: URL
    @ObservationIgnored let imagesDir: URL
    @ObservationIgnored private var saveWork: DispatchWorkItem?

    // Password managers mark secrets with these; never record them.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(settings: Settings) {
        self.settings = settings
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Kairos", isDirectory: true)
        historyURL = base.appendingPathComponent("history.json")
        imagesDir = base.appendingPathComponent("images", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        load()
    }

    /// macOS has no clipboard-changed event, so check the change counter
    /// twice a second. Reading one integer is effectively free.
    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func imageURL(_ item: ClipItem) -> URL? {
        item.imageFile.map { imagesDir.appendingPathComponent($0) }
    }

    func writeToPasteboard(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text ?? "", forType: .string)
        case .files:
            pb.writeObjects((item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            guard let url = imageURL(item), let png = try? Data(contentsOf: url) else { return }
            // Same PNG bytes go back, so the poll recognises it and just moves it to the top.
            pb.setData(png, forType: .png)
            if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation {
                pb.setData(tiff, forType: .tiff)
            }
        }
    }

    func delete(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        removeFile(of: items.remove(at: i))
        scheduleSave()
    }

    func clear() {
        items.forEach(removeFile)
        items.removeAll()
        scheduleSave()
    }

    func trim() {
        while items.count > settings.maxItems {
            removeFile(of: items.removeLast())
        }
        scheduleSave()
    }

    // MARK: - Capture

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        if let item = capture(from: pb) { insert(item) }
    }

    private func capture(from pb: NSPasteboard) -> ClipItem? {
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            return ClipItem(id: UUID(), kind: .files, paths: paths,
                            digest: "f:" + paths.joined(separator: "\n"), date: .now)
        }

        if let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return ClipItem(id: UUID(), kind: .text, text: text,
                            digest: "t:" + Self.hash(Data(text.utf8)), date: .now)
        }

        if let png = Self.pngData(from: pb) {
            let digest = "i:" + Self.hash(png)
            if let existing = items.first(where: { $0.digest == digest }) { return existing }
            let name = UUID().uuidString + ".png"
            do {
                try png.write(to: imagesDir.appendingPathComponent(name))
            } catch {
                return nil
            }
            let rep = NSBitmapImageRep(data: png)
            return ClipItem(id: UUID(), kind: .image, imageFile: name,
                            width: rep?.pixelsWide, height: rep?.pixelsHigh,
                            digest: digest, date: .now)
        }
        return nil
    }

    private func insert(_ item: ClipItem) {
        var item = item
        if let i = items.firstIndex(where: { $0.digest == item.digest }) {
            item = items.remove(at: i)  // keep the original id and image file
        }
        item.date = .now
        items.insert(item, at: 0)
        trim()
    }

    private func removeFile(of item: ClipItem) {
        if let url = imageURL(item) { try? FileManager.default.removeItem(at: url) }
    }

    private static func pngData(from pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).prefix(12).map { String(format: "%02x", $0) }.joined()
    }

    // MARK: - Persistence

    private func load() {
        guard let data = try? Data(contentsOf: historyURL),
              let saved = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        let fm = FileManager.default
        items = saved.filter { item in
            guard item.kind == .image else { return true }
            return imageURL(item).map { fm.fileExists(atPath: $0.path) } ?? false
        }

        // Drop image files no item points to any more.
        let used = Set(items.compactMap(\.imageFile))
        for file in (try? fm.contentsOfDirectory(atPath: imagesDir.path)) ?? [] where !used.contains(file) {
            try? fm.removeItem(at: imagesDir.appendingPathComponent(file))
        }
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let snapshot = items
        let url = historyURL
        let work = DispatchWorkItem {
            if let data = try? JSONEncoder().encode(snapshot) {
                try? data.write(to: url, options: .atomic)
            }
        }
        saveWork = work
        DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + 0.5, execute: work)
    }
}

/// Small, cached thumbnails so images never load at full size.
@MainActor
enum Thumbnails {
    private static let cache = NSCache<NSString, NSImage>()

    static func image(at url: URL, maxPixels: CGFloat = 96) -> NSImage? {
        let key = url.path as NSString
        if let cached = cache.object(forKey: key) { return cached }
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixels,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let image = NSImage(cgImage: cg, size: .zero)
        cache.setObject(image, forKey: key)
        return image
    }
}
